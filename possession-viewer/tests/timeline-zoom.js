// playwright-cli run-code --filename=possession-viewer/tests/timeline-zoom.js
async page => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.goto('http://localhost:8080');
  await page.waitForFunction(() => Boolean(state.reference));
  check(await page.locator('.timeline-tools').count() === 0, 'Timeline zoom adds no toolbar/buttons');
  const initial = await page.evaluate(() => ({ start: state.timelineStart, end: state.timelineEnd }));
  check(initial.start === 0 && initial.end === 199319, 'Default timeline shows the full match');
  await page.locator('#prediction-file').setInputFiles('possession-viewer/tests/fixtures/replacement.csv');
  await page.waitForFunction(() => Boolean(state.predictions));
  await page.locator('#jump-reference').click();
  check(await page.evaluate(() => state.timelineStart === 11185 && state.timelineEnd === 18685), 'Existing reference link fits the public window');
  check(await page.locator('#seek').getAttribute('min') === '11185' && await page.locator('#seek').getAttribute('max') === '18684', 'Seek range follows the visible frames');
  await page.locator('#frame-input').fill('15355');
  await page.locator('#frame-input').press('Enter');
  const bounds = await page.locator('#timeline-wrap').boundingBox();
  const x = Math.round(bounds.x + (15355 - 11185) / 7500 * bounds.width);
  await page.mouse.move(x, bounds.y + 25);
  const anchorBefore = await page.evaluate(fraction => state.timelineStart + fraction * (state.timelineEnd - state.timelineStart), (x - bounds.x) / bounds.width);
  await page.mouse.wheel(0, -400);
  await page.waitForFunction(() => state.timelineEnd - state.timelineStart < 7500);
  const anchorAfter = await page.evaluate(fraction => state.timelineStart + fraction * (state.timelineEnd - state.timelineStart), (x - bounds.x) / bounds.width);
  check(Math.abs(anchorBefore - anchorAfter) <= 1, 'Wheel zoom anchors at the cursor');
  check(await page.evaluate(() => state.frame === 15355 && state.zoom === 1), 'Timeline zoom does not seek or alter video zoom');
  await page.mouse.wheel(0, -5000);
  await page.waitForFunction(() => state.timelineEnd - state.timelineStart === 25);
  check(await page.locator('#timeline-start-label').textContent() !== await page.locator('#timeline-end-label').textContent(), 'Frame bounds remain readable at maximum zoom');
  const beforePan = await page.evaluate(() => state.timelineStart);
  await page.keyboard.down('Shift');
  await page.mouse.wheel(0, 600);
  await page.keyboard.up('Shift');
  await page.waitForFunction(start => state.timelineStart > start, beforePan);
  check(await page.evaluate(() => state.frame === 15355), 'Panning does not seek');
  const view = await page.evaluate(() => ({ start: state.timelineStart, end: state.timelineEnd }));
  await page.mouse.click(bounds.x + bounds.width / 2, bounds.y + 9);
  check(await page.evaluate(v => Math.abs(state.frame - (v.start + (v.end - v.start - 1) / 2)) <= 1, view), 'Click seeks the correct frame inside the zoomed viewport');
  await page.locator('#frame-input').fill('18000');
  await page.locator('#frame-input').press('Enter');
  check(await page.evaluate(() => state.timelineStart <= 18000 && state.timelineEnd > 18000 && state.timelineEnd - state.timelineStart === 25), 'Jumping to a frame keeps it visible without losing zoom');
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + 25);
  await page.keyboard.down('Shift');
  await page.mouse.wheel(0, 100000000);
  await page.keyboard.up('Shift');
  await page.waitForFunction(() => state.timelineEnd === FRAME_COUNT);
  check(await page.evaluate(() => state.timelineStart >= 0 && state.timelineEnd <= FRAME_COUNT), 'Panning clamps to the match bounds');
  await page.mouse.wheel(0, 100000);
  await page.waitForFunction(() => state.timelineStart === 0 && state.timelineEnd === FRAME_COUNT);
  check(await page.locator('#seek').getAttribute('max') === '199318', 'Zooming all the way out restores full-match seeking');
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Timeline labels fit on mobile');
  await page.setViewportSize({ width: 1280, height: 720 });
  return 'PASS: gesture-only timeline zoom, cursor anchor, reference fit, precise seeking, pan, bounds, auto-follow, full zoom-out and mobile layout';
}
